import type { Block } from './blocks.ts';
import { readZip, writeZip } from './zip.ts';

const xmlEscape = (s: string) =>
  s
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const decodeEntities = (s: string) =>
  s.replace(/&(#x[0-9a-f]+|#\d+|amp|lt|gt|quot|apos);/gi, (_, e: string) => {
    const k = e.toLowerCase();
    if (k === 'amp') return '&';
    if (k === 'lt') return '<';
    if (k === 'gt') return '>';
    if (k === 'quot') return '"';
    if (k === 'apos') return "'";
    const code = k.startsWith('#x') ? parseInt(k.slice(2), 16) : parseInt(k.slice(1), 10);
    return Number.isFinite(code) && code <= 0x10ffff ? String.fromCodePoint(code) : '';
  });

/** Extracts paragraph text from a DOCX package. Never executes or follows embedded content. */
export function docxToText(buf: Buffer): string {
  const files = readZip(buf, new Set(['word/document.xml']));
  const xml = files.get('word/document.xml');
  if (!xml) throw new Error('This file is not a Word document (word/document.xml missing).');
  const doc = xml.toString('utf8');
  const paragraphs = doc.match(/<w:p[\s>][\s\S]*?<\/w:p>|<w:p\/>/g) ?? [];
  return paragraphs
    .map((p) => {
      let text = '';
      for (const m of p.matchAll(/<w:t(?:\s[^>]*)?>([\s\S]*?)<\/w:t>|<w:tab\/>|<w:br\/>/g)) {
        if (m[0] === '<w:tab/>') text += '\t';
        else if (m[0] === '<w:br/>') text += '\n';
        else text += decodeEntities(m[1] ?? '');
      }
      const isBullet = /<w:numPr>/.test(p);
      return isBullet && text ? `• ${text}` : text;
    })
    .join('\n');
}

const STYLE: Record<Block['type'], string> = {
  title: 'Title',
  subtitle: 'Subtitle',
  meta: 'Meta',
  heading: 'Heading1',
  role: 'Heading2',
  para: 'Normal',
  bullet: 'ListBullet',
};

function paragraph(b: Block): string {
  const numbering = b.type === 'bullet' ? '<w:numPr><w:ilvl w:val="0"/><w:numId w:val="1"/></w:numPr>' : '';
  return `<w:p><w:pPr><w:pStyle w:val="${STYLE[b.type]}"/>${numbering}</w:pPr><w:r><w:t xml:space="preserve">${xmlEscape(b.text)}</w:t></w:r></w:p>`;
}

